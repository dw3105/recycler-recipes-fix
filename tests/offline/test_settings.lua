-- Owner contract tests S-1, S-2. Frozen: lanes never edit or weaken.
local env = dofile("tests/offline/env.lua")

local function base()
  env.fresh()
  env.item("plate"); env.item("copper"); env.item("gear"); env.item("chest"); env.item("widget"); env.item("orphan")
end

describe("S-1 excluded", function()
  it("excluded missing item gets nothing", function()
    base()
    env.recipe("widget", {gear = 8})
    local rep = env.run({excluded = {widget = true}, self_recycling = false})
    eq(env.results("widget-recycling"), "NONE", "not added")
    eq(env.has(rep.excluded, "widget-recycling"), true, "report excluded")
  end)
  it("excluded stale item keeps old recycling", function()
    base()
    local r = env.recipe("chest", {plate = 8})
    env.lib.generate_recycling_recipe(r)
    r.ingredients = {{type = "item", name = "copper", amount = 8}}
    env.run({excluded = {chest = true}})
    eq(env.results("chest-recycling"), "plate=2", "kept")
  end)
  it("excluded item gets no self-recycling", function()
    base()
    env.run({excluded = {orphan = true}})
    eq(env.results("orphan-recycling"), "NONE", "no self")
  end)
end)

describe("S-2 self-recycling switch", function()
  it("on: item with no recycling gets self-recycling", function()
    base()
    local rep = env.run({self_recycling = true})
    local r = data.raw.recipe["orphan-recycling"]
    eq(r and r.results[1].name, "orphan", "returns itself")
    eq(r and r.results[1][env.prob_key], 0.25, "25%")
    eq(env.has(rep.self_added, "orphan-recycling"), true, "report")
  end)
  it("off: no self-recycling added", function()
    base()
    env.run({self_recycling = false})
    eq(env.results("orphan-recycling"), "NONE", "none")
  end)
  it("barrel and auto_recycle false skipped", function()
    base()
    env.item("water-barrel"); env.item("nope", {auto_recycle = false})
    env.run({self_recycling = true})
    eq(env.results("water-barrel-recycling"), "NONE", "barrel")
    eq(env.results("nope-recycling"), "NONE", "auto_recycle false")
  end)
end)
