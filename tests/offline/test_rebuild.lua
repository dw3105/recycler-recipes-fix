-- Owner contract tests R-2..R-9, L-1. Frozen: lanes never edit or weaken.
local env = dofile("tests/offline/env.lua")

local function base()
  env.fresh()
  env.item("plate"); env.item("copper"); env.item("gear"); env.item("chest"); env.item("widget")
end

describe("R-2 missing", function()
  it("late recipe gets game-built recycling", function()
    base()
    env.recipe("widget", {gear = 8, copper = 4})
    local rep = env.run()
    eq(env.results("widget-recycling"), "copper=1,gear=2", "results")
    eq(data.raw.recipe["widget-recycling"].localised_name[1], "recipe-name.recycling", "game-built name")
    eq(env.has(rep.added, "widget-recycling <- widget"), true, "report added")
  end)
end)

describe("R-3 stale", function()
  it("changed source recipe replaces game-built recycling", function()
    base()
    local r = env.recipe("chest", {plate = 8})
    env.lib.generate_recycling_recipe(r)
    r.ingredients = {{type = "item", name = "copper", amount = 8}}
    local rep = env.run()
    eq(env.results("chest-recycling"), "copper=2", "results")
    eq(env.has(rep.fixed, "chest-recycling <- chest"), true, "report fixed")
  end)
end)

describe("R-4 still valid", function()
  it("matching game-built recycling keeps same table", function()
    base()
    env.lib.generate_recycling_recipe(env.recipe("chest", {plate = 8}))
    local before = data.raw.recipe["chest-recycling"]
    local rep = env.run()
    eq(rawequal(data.raw.recipe["chest-recycling"], before), true, "same table")
    eq(#rep.added + #rep.fixed, 0, "no changes")
  end)
  it("second source recipe matching keeps first", function()
    base()
    env.lib.generate_recycling_recipe(env.recipe("chest", {plate = 8}))
    env.recipe("chest-alt", {copper = 8}, "chest")
    local before = data.raw.recipe["chest-recycling"]
    env.run()
    eq(rawequal(data.raw.recipe["chest-recycling"], before), true, "same table")
  end)
end)

describe("R-5 self-recycling", function()
  it("self-recycling replaced when source recipe exists", function()
    base()
    env.lib.generate_self_recycling_recipe(data.raw.item.widget)
    env.recipe("widget", {gear = 8})
    local rep = env.run()
    eq(env.results("widget-recycling"), "gear=2", "results")
    eq(env.has(rep.fixed, "widget-recycling <- widget"), true, "report fixed")
  end)
end)

describe("R-6 hand-made", function()
  it("hand-made recycling untouched after source change", function()
    base()
    local r = env.recipe("chest", {plate = 8})
    data.raw.recipe["chest-recycling"] = {type = "recipe", name = "chest-recycling", localised_name = "custom",
      category = "recycling", categories = {"recycling"}, ingredients = {{type = "item", name = "chest", amount = 1}},
      results = {{type = "item", name = "plate", amount = 3}}}
    local before = data.raw.recipe["chest-recycling"]
    r.ingredients = {{type = "item", name = "copper", amount = 8}}
    local rep = env.run()
    eq(rawequal(data.raw.recipe["chest-recycling"], before), true, "same table")
    eq(env.results("chest-recycling"), "plate=3", "results")
    eq(#rep.fixed, 0, "no fixed")
  end)
end)

describe("R-7 game-built test", function()
  it("game name with foreign icon counts as hand-made", function()
    base()
    local r = env.recipe("chest", {plate = 8})
    env.lib.generate_recycling_recipe(r)
    data.raw.recipe["chest-recycling"].icons[1].icon = "__other__/graphics/icons/recycling.png"
    r.ingredients = {{type = "item", name = "copper", amount = 8}}
    env.run()
    eq(env.results("chest-recycling"), "plate=2", "kept")
  end)
end)

describe("R-8 rejected source", function()
  it("auto_recycle false keeps current recycling", function()
    base()
    env.lib.generate_self_recycling_recipe(data.raw.item.widget)
    local before = data.raw.recipe["widget-recycling"]
    env.recipe("widget", {gear = 8}, nil, {auto_recycle = false})
    env.run()
    eq(rawequal(data.raw.recipe["widget-recycling"], before), true, "same table")
  end)
end)

describe("R-9 unlocks", function()
  it("one unlock per added or replaced recipe, none for kept", function()
    base()
    env.lib.generate_recycling_recipe(env.recipe("chest", {plate = 8}))
    env.recipe("widget", {gear = 8})
    local kept = env.unlocks("chest-recycling")
    env.run()
    eq(env.unlocks("chest-recycling"), kept, "kept recipe unlock count unchanged")
    eq(env.unlocks("widget-recycling"), env.fv == "2.1" and 1 or 0, "added recipe unlocks")
  end)
  it("stale replace leaves one unlock", function()
    base()
    local r = env.recipe("chest", {plate = 8})
    env.lib.generate_recycling_recipe(r)
    r.ingredients = {{type = "item", name = "copper", amount = 8}}
    env.run()
    eq(env.unlocks("chest-recycling"), env.fv == "2.1" and 1 or 0, "unlocks")
  end)
end)

describe("L-1 report", function()
  it("log has prefix, counts and per-recipe line", function()
    base()
    env.recipe("widget", {gear = 8})
    env.run()
    local all = table.concat(env.logs, "\n")
    eq(all:find("[recycler-recipes-fix] added: 1", 1, true) ~= nil, true, "count line")
    eq(all:find("[recycler-recipes-fix]   widget-recycling <- widget", 1, true) ~= nil, true, "recipe line")
    eq(all:find("[recycler-recipes-fix] fixed: 0", 1, true) ~= nil, true, "fixed count")
    eq(all:find("[recycler-recipes-fix] excluded: 0", 1, true) ~= nil, true, "excluded count")
  end)
end)
